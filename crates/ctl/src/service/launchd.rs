//! launchd user agent (macOS).

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};
use std::time::Duration;

use credential_bridge_core::paths;

use super::{DaemonSpec, InstalledSpec, ServiceInfo, ServiceManager};
use crate::util::{retry, run, wait_until};

const LABEL: &str = "local.credential-bridge.daemon";

#[derive(Debug)]
pub struct Launchd {
    plist_path: PathBuf,
    log_path: PathBuf,
}

impl Launchd {
    pub fn new() -> anyhow::Result<Self> {
        let home = paths::home_dir()?;
        Ok(Self {
            plist_path: home.join("Library/LaunchAgents").join(format!("{LABEL}.plist")),
            log_path: home.join("Library/Logs/credential-bridge/credential-bridged.log"),
        })
    }

    fn domain() -> String {
        format!("gui/{}", rustix::process::getuid().as_raw())
    }

    fn target() -> String {
        format!("{}/{LABEL}", Self::domain())
    }

    fn launchctl(args: &[&str]) -> anyhow::Result<()> {
        run(Command::new("launchctl").args(args))
    }

    fn is_loaded() -> bool {
        Command::new("launchctl")
            .args(["print", &Self::target()])
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .is_ok_and(|status| status.success())
    }

    /// Loads the agent. launchd may still be tearing down a job that was just
    /// booted out ("Bootstrap failed: 5: Input/output error"), so wait for
    /// that and retry a few times.
    fn bootstrap(&self) -> anyhow::Result<()> {
        wait_until(Duration::from_secs(5), POLL, || !Self::is_loaded());
        retry(BOOTSTRAP_ATTEMPTS, POLL * 5, || {
            Self::launchctl(&["bootstrap", &Self::domain(), &self.plist_path.to_string_lossy()])
        })
    }
}

const POLL: Duration = Duration::from_millis(100);
const BOOTSTRAP_ATTEMPTS: usize = 4;

fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;").replace('<', "&lt;").replace('>', "&gt;").replace('"', "&quot;")
}

pub fn render_plist(daemon: &DaemonSpec, log_path: &Path) -> String {
    let args: String = std::iter::once(daemon.program.to_string_lossy().into_owned())
        .chain(daemon.args.iter().cloned())
        .map(|arg| format!("        <string>{}</string>\n", xml_escape(&arg)))
        .collect();
    let log = xml_escape(&log_path.to_string_lossy());
    format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by credential-bridge-ctl; re-run `credential-bridge-ctl service install` to update. -->
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>{LABEL}</string>
    <key>ProgramArguments</key>
    <array>
{args}    </array>
    <key>EnvironmentVariables</key>
    <dict>
{env}    </dict>
    <key>RunAtLoad</key>
    <true/>
    <key>KeepAlive</key>
    <dict>
        <key>SuccessfulExit</key>
        <false/>
    </dict>
    <key>StandardOutPath</key>
    <string>{log}</string>
    <key>StandardErrorPath</key>
    <string>{log}</string>
</dict>
</plist>
"#,
        env = daemon
            .env
            .iter()
            .map(|(name, value)| format!(
                "        <key>{}</key>\n        <string>{}</string>\n",
                xml_escape(name),
                xml_escape(value)
            ))
            .collect::<String>(),
    )
}

fn xml_unescape(s: &str) -> String {
    s.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", "\"")
        .replace("&apos;", "'")
        .replace("&amp;", "&")
}

/// The `<string>`s of the element that follows `<key>{key}</key>`.
fn strings_after(plist: &str, key: &str) -> Vec<String> {
    let Some(start) = plist.find(&format!("<key>{key}</key>")) else { return Vec::new() };
    let rest = &plist[start..];
    let end = ["</array>", "</dict>"].iter().filter_map(|tag| rest.find(tag)).min().unwrap_or(rest.len());
    let block = &rest[..end];
    let mut out = Vec::new();
    let mut tail = block;
    while let Some(open) = tail.find("<string>") {
        let from = open + "<string>".len();
        let Some(len) = tail[from..].find("</string>") else { break };
        out.push(xml_unescape(&tail[from..from + len]));
        tail = &tail[from + len..];
    }
    out
}

/// Program, arguments and environment of a plist written by [`render_plist`].
fn plist_spec(plist: &str) -> Option<InstalledSpec> {
    let exec = strings_after(plist, "ProgramArguments");
    let (program, args) = exec.split_first()?;
    let env_block = plist.find("<key>EnvironmentVariables</key>").map(|i| &plist[i..]).unwrap_or_default();
    let env_block = &env_block[..env_block.find("</dict>").unwrap_or(env_block.len())];
    let keys: Vec<String> = env_block
        .split("<key>")
        .skip(2)
        .filter_map(|part| part.split_once("</key>").map(|(k, _)| xml_unescape(k)))
        .collect();
    let values = strings_after(plist, "EnvironmentVariables");
    Some(InstalledSpec {
        program: PathBuf::from(program),
        args: args.to_vec(),
        env: keys.into_iter().zip(values).collect(),
    })
}

/// First entry of `ProgramArguments`.
fn plist_program(plist: &str) -> Option<PathBuf> {
    plist_spec(plist).map(|spec| spec.program)
}

impl ServiceManager for Launchd {
    fn definition_path(&self) -> &Path {
        &self.plist_path
    }

    fn install(&self, daemon: &DaemonSpec, start: bool) -> anyhow::Result<()> {
        if Self::is_loaded() {
            let _ = Self::launchctl(&["bootout", &Self::target()]);
        }
        for dir in [self.plist_path.parent(), self.log_path.parent()].into_iter().flatten() {
            fs::create_dir_all(dir)?;
        }
        fs::write(&self.plist_path, render_plist(daemon, &self.log_path))?;
        if start {
            self.bootstrap()?;
        }
        Ok(())
    }

    fn uninstall(&self) -> anyhow::Result<()> {
        if Self::is_loaded() {
            let _ = Self::launchctl(&["bootout", &Self::target()]);
        }
        fs::remove_file(&self.plist_path)?;
        Ok(())
    }

    fn start(&self) -> anyhow::Result<()> {
        if Self::is_loaded() { Self::launchctl(&["kickstart", &Self::target()]) } else { self.bootstrap() }
    }

    fn stop(&self) -> anyhow::Result<()> {
        // A clean exit is not restarted (KeepAlive.SuccessfulExit = false).
        Self::launchctl(&["kill", "SIGTERM", &Self::target()])
    }

    fn restart(&self) -> anyhow::Result<()> {
        if Self::is_loaded() {
            Self::launchctl(&["kickstart", "-k", &Self::target()])
        } else {
            self.bootstrap()
        }
    }

    fn reload(&self) -> anyhow::Result<()> {
        Self::launchctl(&["kill", "SIGHUP", &Self::target()])
    }

    fn status(&self) -> anyhow::Result<()> {
        if !Self::is_loaded() {
            println!("installed but not loaded; run `credential-bridge-ctl service start`");
            return Ok(());
        }
        Self::launchctl(&["print", &Self::target()])
    }

    fn logs(&self, follow: bool, lines: usize) -> anyhow::Result<()> {
        let mut cmd = Command::new("tail");
        cmd.args(["-n", &lines.to_string()]);
        if follow {
            cmd.arg("-F");
        }
        cmd.arg(&self.log_path);
        super::print_log_lines(cmd, super::format_file_line)
    }

    fn info(&self) -> ServiceInfo {
        let output =
            Command::new("launchctl").args(["print", &Self::target()]).stderr(Stdio::null()).output();
        let text = output.map(|out| String::from_utf8_lossy(&out.stdout).into_owned()).unwrap_or_default();
        let pid = text.lines().find_map(|line| line.trim().strip_prefix("pid = ")?.trim().parse().ok());
        ServiceInfo { pid, since: None }
    }

    fn installed_program(&self) -> Option<PathBuf> {
        plist_program(&fs::read_to_string(&self.plist_path).ok()?)
    }

    fn installed_spec(&self) -> Option<InstalledSpec> {
        plist_spec(&fs::read_to_string(&self.plist_path).ok()?)
    }

    fn is_active(&self) -> bool {
        Command::new("launchctl")
            .args(["print", &Self::target()])
            .stderr(Stdio::null())
            .output()
            .is_ok_and(|out| String::from_utf8_lossy(&out.stdout).contains("state = running"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_a_plist() {
        let plist = render_plist(
            &DaemonSpec {
                program: "/Users/me/bin/credential-bridged".into(),
                args: vec!["run".into()],
                env: vec![("PATH".into(), "/usr/bin".into())],
            },
            Path::new("/Users/me/Library/Logs/x.log"),
        );
        assert!(
            plist.contains(
                "<string>/Users/me/bin/credential-bridged</string>\n        <string>run</string>\n"
            )
        );
        assert!(plist.contains(&format!("<string>{LABEL}</string>")));
        assert_eq!(plist_program(&plist), Some(PathBuf::from("/Users/me/bin/credential-bridged")));
        let spec = plist_spec(&plist).unwrap();
        assert_eq!(spec.args, ["run"]);
        assert_eq!(spec.env, [("PATH".to_owned(), "/usr/bin".to_owned())]);
    }
}
