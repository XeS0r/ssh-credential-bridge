//! systemd user service (Linux).

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use credential_bridge_core::paths;

use super::{DaemonSpec, InstalledSpec, ServiceInfo, ServiceManager};
use crate::util::run;

const UNIT: &str = "credential-bridged.service";

#[derive(Debug)]
pub struct Systemd {
    unit_path: PathBuf,
}

impl Systemd {
    pub fn new() -> anyhow::Result<Self> {
        // Where the user manager looks for units: its own XDG_CONFIG_HOME,
        // which need not be the one of this shell.
        let manager_env = Command::new("systemctl")
            .args(["--user", "show-environment"])
            .stderr(Stdio::null())
            .output()
            .map(|out| String::from_utf8_lossy(&out.stdout).into_owned())
            .unwrap_or_default();
        Ok(Self { unit_path: unit_dir(&manager_env, &paths::home_dir()?).join(UNIT) })
    }

    fn systemctl(args: &[&str]) -> anyhow::Result<()> {
        run(Command::new("systemctl").arg("--user").args(args))
    }
}

/// `$XDG_CONFIG_HOME/systemd/user` of the user manager, `~/.config/systemd/user` by default.
fn unit_dir(manager_env: &str, home: &Path) -> PathBuf {
    manager_env
        .lines()
        .find_map(|line| line.strip_prefix("XDG_CONFIG_HOME="))
        .filter(|dir| dir.starts_with('/'))
        .map_or_else(|| home.join(".config"), PathBuf::from)
        .join("systemd/user")
}

/// Quotes one ExecStart argument (systemd.service(5) "COMMAND LINES").
fn exec_quote(arg: &str) -> String {
    let escaped = arg.replace('\\', "\\\\").replace('"', "\\\"").replace('%', "%%").replace('$', "$$");
    format!("\"{escaped}\"")
}

pub fn render_unit(daemon: &DaemonSpec) -> String {
    let exec = std::iter::once(daemon.program.to_string_lossy().into_owned())
        .chain(daemon.args.iter().cloned())
        .map(|arg| exec_quote(&arg))
        .collect::<Vec<_>>()
        .join(" ");
    let environment: String = daemon
        .env
        .iter()
        .map(|(name, value)| format!("Environment={}\n", env_quote(&format!("{name}={value}"))))
        .collect();
    // Not every system has /bin/kill (NixOS does not); `service reload` itself
    // uses `systemctl kill`, this is for a plain `systemctl --user reload`.
    let kill = crate::util::which("kill")
        .map_or_else(|| "/bin/kill".to_owned(), |p| p.to_string_lossy().into_owned());
    format!(
        "# Generated by credential-bridge-ctl; re-run `credential-bridge-ctl service install` to update.\n\
         [Unit]\n\
         Description=credential-bridge daemon (git credentials for SSH remotes)\n\
         Documentation=man:credential-bridged(1)\n\
         \n\
         [Service]\n\
         Type=notify\n\
         NotifyAccess=main\n\
         ExecStart={exec}\n\
         ExecReload={kill} -HUP $MAINPID\n\
         {environment}\
         Restart=on-failure\n\
         RestartSec=2\n\
         NoNewPrivileges=yes\n\
         \n\
         [Install]\n\
         WantedBy=default.target\n"
    )
}

/// Quotes one `Environment=` assignment. Unlike ExecStart, systemd expands
/// no `$` there, only `%` specifiers.
fn env_quote(assignment: &str) -> String {
    let escaped = assignment.replace('\\', "\\\\").replace('"', "\\\"").replace('%', "%%");
    format!("\"{escaped}\"")
}

/// Splits a unit line value into words, undoing [`exec_quote`] (or, with
/// `dollars` false, [`env_quote`]).
fn unquote_words(value: &str, dollars: bool) -> Vec<String> {
    let mut words = Vec::new();
    let mut chars = value.trim().chars().peekable();
    while let Some(&c) = chars.peek() {
        if c.is_whitespace() {
            chars.next();
            continue;
        }
        let mut word = String::new();
        if c == '"' {
            chars.next();
            while let Some(c) = chars.next() {
                match c {
                    '"' => break,
                    '\\' => word.extend(chars.next()),
                    c => word.push(c),
                }
            }
        } else {
            while let Some(&c) = chars.peek() {
                if c.is_whitespace() {
                    break;
                }
                word.push(c);
                chars.next();
            }
        }
        word = word.replace("%%", "%");
        if dollars {
            word = word.replace("$$", "$");
        }
        words.push(word);
    }
    words
}

/// Program, arguments and environment of a unit written by [`render_unit`].
fn unit_spec(unit: &str) -> Option<InstalledSpec> {
    let exec = unquote_words(unit.lines().find_map(|line| line.strip_prefix("ExecStart="))?, true);
    let (program, args) = exec.split_first()?;
    let env = unit
        .lines()
        .filter_map(|line| line.strip_prefix("Environment="))
        .flat_map(|value| unquote_words(value, false))
        .filter_map(|assignment| assignment.split_once('=').map(|(k, v)| (k.to_owned(), v.to_owned())))
        .collect();
    Some(InstalledSpec { program: PathBuf::from(program), args: args.to_vec(), env })
}

/// First word of `ExecStart=`.
fn exec_program(unit: &str) -> Option<PathBuf> {
    unit_spec(unit).map(|spec| spec.program)
}

impl ServiceManager for Systemd {
    fn definition_path(&self) -> &Path {
        &self.unit_path
    }

    fn install(&self, daemon: &DaemonSpec, start: bool) -> anyhow::Result<()> {
        if let Some(dir) = self.unit_path.parent() {
            fs::create_dir_all(dir)?;
        }
        fs::write(&self.unit_path, render_unit(daemon))?;
        Self::systemctl(&["daemon-reload"])?;
        if start {
            Self::systemctl(&["enable", "--now", UNIT])?;
            // Picks up a changed unit if the service was already running.
            Self::systemctl(&["restart", UNIT])
        } else {
            Self::systemctl(&["enable", UNIT])
        }
    }

    fn uninstall(&self) -> anyhow::Result<()> {
        let _ = Self::systemctl(&["disable", "--now", UNIT]);
        fs::remove_file(&self.unit_path)?;
        Self::systemctl(&["daemon-reload"])
    }

    fn start(&self) -> anyhow::Result<()> {
        Self::systemctl(&["start", UNIT])
    }

    fn stop(&self) -> anyhow::Result<()> {
        Self::systemctl(&["stop", UNIT])
    }

    fn restart(&self) -> anyhow::Result<()> {
        Self::systemctl(&["restart", UNIT])
    }

    fn reload(&self) -> anyhow::Result<()> {
        // Independent of the unit's ExecReload and of where `kill` lives.
        Self::systemctl(&["kill", "--signal=HUP", "--kill-whom=main", UNIT])
    }

    fn status(&self) -> anyhow::Result<()> {
        // `status` exits with 3 for an inactive unit; that is not an error here.
        Command::new("systemctl").args(["--user", "status", "--no-pager", UNIT]).status()?;
        Ok(())
    }

    fn logs(&self, follow: bool, lines: usize) -> anyhow::Result<()> {
        let mut cmd = Command::new("journalctl");
        cmd.args(["--user", "--no-pager", "-o", "short-iso", "--no-hostname", "-u", UNIT]);
        cmd.args(["-n", &lines.to_string()]);
        if follow {
            cmd.arg("-f");
        }
        super::print_log_lines(cmd, super::format_journal_line)
    }

    fn info(&self) -> ServiceInfo {
        let output = Command::new("systemctl")
            .args(["--user", "show", UNIT, "-p", "MainPID", "-p", "ActiveEnterTimestamp"])
            .stderr(Stdio::null())
            .output();
        let text = output.map(|out| String::from_utf8_lossy(&out.stdout).into_owned()).unwrap_or_default();
        let value = |key: &str| {
            text.lines().find_map(|line| line.strip_prefix(key)?.strip_prefix('=')).map(str::trim)
        };
        ServiceInfo {
            pid: value("MainPID").and_then(|pid| pid.parse().ok()).filter(|&pid: &u32| pid != 0),
            since: value("ActiveEnterTimestamp").filter(|ts| !ts.is_empty()).map(str::to_owned),
        }
    }

    fn installed_program(&self) -> Option<PathBuf> {
        exec_program(&fs::read_to_string(&self.unit_path).ok()?)
    }

    fn installed_spec(&self) -> Option<InstalledSpec> {
        unit_spec(&fs::read_to_string(&self.unit_path).ok()?)
    }

    fn is_active(&self) -> bool {
        Command::new("systemctl")
            .args(["--user", "is-active", "--quiet", UNIT])
            .stdout(Stdio::null())
            .stderr(Stdio::null())
            .status()
            .is_ok_and(|status| status.success())
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders_a_unit() {
        let unit = render_unit(&DaemonSpec {
            program: "/home/me/bin/credential-bridged".into(),
            args: vec!["run".into(), "--config".into(), "/home/me/my 100%.toml".into()],
            env: vec![
                ("PATH".into(), "/home/me/.nix-profile/bin:/usr/bin".into()),
                ("XDG_STATE_HOME".into(), "/home/me/state".into()),
            ],
        });
        assert!(unit.contains(
            "ExecStart=\"/home/me/bin/credential-bridged\" \"run\" \"--config\" \"/home/me/my 100%%.toml\"\n"
        ));
        assert!(unit.contains("Environment=\"PATH=/home/me/.nix-profile/bin:/usr/bin\"\n"));
        assert!(unit.contains("Environment=\"XDG_STATE_HOME=/home/me/state\"\n"));
        assert!(unit.contains("Type=notify\nNotifyAccess=main\n"));
        assert!(unit.contains("kill -HUP $MAINPID\n"));
        assert_eq!(exec_program(&unit), Some(PathBuf::from("/home/me/bin/credential-bridged")));
        assert_eq!(exec_program("ExecStart=/usr/bin/x run\n"), Some(PathBuf::from("/usr/bin/x")));
        assert_eq!(exec_program("[Unit]\n"), None);
    }

    #[test]
    fn environment_values_keep_dollars_and_round_trip() {
        let spec = DaemonSpec {
            program: "/home/me/bin/credential-bridged".into(),
            args: vec!["run".into(), "--config".into(), "/home/me/a b/c$1 100%.toml".into()],
            env: vec![
                ("PATH".into(), "/home/me/a$b:/usr/bin".into()),
                ("XDG_STATE_HOME".into(), "/s 100%".into()),
            ],
        };
        let unit = render_unit(&spec);
        assert!(unit.contains("Environment=\"PATH=/home/me/a$b:/usr/bin\"\n"), "{unit}");
        let back = unit_spec(&unit).unwrap();
        assert_eq!(back.program, spec.program);
        assert_eq!(back.args, spec.args);
        assert_eq!(back.env, spec.env);
    }

    #[test]
    fn units_go_where_the_user_manager_looks() {
        let home = Path::new("/home/me");
        assert_eq!(unit_dir("PATH=/bin\n", home), PathBuf::from("/home/me/.config/systemd/user"));
        assert_eq!(
            unit_dir("XDG_CONFIG_HOME=/home/me/cfg\n", home),
            PathBuf::from("/home/me/cfg/systemd/user")
        );
    }
}
